import { ARG_SHAPES, TOOL_META, type ToolName } from "@munshi/mcp-common";
import { randomBytes } from "node:crypto";
import { LlmError, type LlmAdapter } from "../llm/types.js";
import { PolicyRule } from "./policy.js";

/** A compile failure with a message that is safe and useful to show to the user. */
export class PolicyCompileError extends Error {}

const agentTools = (Object.keys(TOOL_META) as ToolName[]).filter((t) => TOOL_META[t].agentCallable);

const toolDoc = agentTools
  .map((t) => `- ${t} (${TOOL_META[t].riskTier}); args: ${Object.keys(ARG_SHAPES[t]).join(", ")}`)
  .join("\n");

export const COMPILER_SYSTEM = `You translate ONE plain-language rule typed by the user into ONE JSON policy rule for a deterministic Guard.
You only produce a draft. A human reviews it and must confirm before it is saved; you can never activate anything.

Tools the agent can call:
${toolDoc}

Rule format (strict JSON, no extra keys):
{"rule":{
  "description": "short plain-English summary of the user's intent",
  "match": {
    "tool": "<one tool name above, or \\"*\\" for any tool>",
    "argsCondition": { "<argName>": <condition> },   // optional; only args that exist on that tool
    "tainted": true|false,                            // optional: value came from email content
    "allSensitiveAllowlisted": true|false,            // optional: every recipient/attendee is your own address or a saved contact
    "minObligationConfidence": 0..1                   // optional
  },
  "decision": "allow" | "require_approval" | "block",
  "reason": "why, shown to the user when it fires"
}}
<condition> is a literal, or exactly one of: {"contains":"text"} {"gte":n} {"lte":n} {"in":[...]} {"exists":true|false}.
String matching is case-insensitive; "contains" on an array arg (like "to") matches if any element contains the text.

Guidance:
- "never ... without asking" / "always ask before ..." -> require_approval. "never / don't ever / block ..." -> block.
- Only use "allow" when the user clearly asks to stop being asked or to automate something.
- Pick the MOST CONSERVATIVE rule that faithfully expresses the request. Do not invent arguments or tools.
- If the request cannot be expressed with these tools and arguments, reply {"error":"<one sentence why>"} instead.
Reply with ONLY the JSON object.`;

const RULE_KEYS_FOR_ID = /[^a-z0-9]+/g;

export function describeCondition(arg: string, c: unknown): string {
  if (c !== null && typeof c === "object") {
    const o = c as Record<string, unknown>;
    if ("contains" in o) return `${arg} contains "${String(o.contains)}"`;
    if ("gte" in o) return `${arg} is at least ${String(o.gte)}`;
    if ("lte" in o) return `${arg} is at most ${String(o.lte)}`;
    if ("in" in o) return `${arg} is one of ${(o.in as unknown[]).map((v) => `"${String(v)}"`).join(", ")}`;
    if ("exists" in o) return o.exists ? `${arg} is provided` : `${arg} is not provided`;
  }
  return `${arg} equals "${String(c)}"`;
}

/** Deterministic plain-English readback of what a rule will do. Generated by code, never by the LLM. */
export function describeRule(rule: PolicyRule): string {
  const m = rule.match;
  const conds: string[] = [];
  for (const [k, v] of Object.entries(m.argsCondition ?? {})) conds.push(describeCondition(k, v));
  if (m.tainted === true) conds.push("a value came from email content (tainted)");
  if (m.tainted === false) conds.push("no value came from email content");
  if (m.allSensitiveAllowlisted === true) conds.push("every recipient/attendee is you or a saved contact");
  if (m.allSensitiveAllowlisted === false) conds.push("some recipient/attendee is NOT you or a saved contact");
  if (m.minObligationConfidence !== undefined) conds.push(`the obligation's extraction confidence is at least ${m.minObligationConfidence}`);
  const when = `Whenever the agent calls ${m.tool === "*" ? "any tool" : m.tool}${conds.length ? ` and ${conds.join(" and ")}` : ""}`;
  const then = {
    allow: "allow it automatically (the Guard's built-in protections still apply)",
    require_approval: "pause and ask for your approval first",
    block: "block it",
  }[rule.decision];
  return `${when}, ${then}.`;
}

/** Deterministic notes shown next to the draft so the user knows what it does and does not change. */
export function ruleWarnings(rule: PolicyRule): string[] {
  const w: string[] = [];
  if (rule.decision === "allow") w.push("This rule makes Munshi act without asking. The most restrictive matching rule still wins, and built-in protections (e.g. email always needs approval, tainted actions are never auto-allowed) cannot be overridden.");
  if (rule.match.tool === "send_email" && rule.decision === "require_approval")
    w.push("Sending email already always needs your approval (built-in), so this rule adds a clearer reason but does not change when you are asked.");
  if (rule.match.tool === "*" && rule.decision === "block") w.push("This blocks every tool call that matches, which can stop most of Munshi from working.");
  return w;
}

/** Strict validation of a candidate: schema + real tool + real argument names. Throws PolicyCompileError. */
export function validateCandidate(raw: unknown): PolicyRule {
  if (!raw || typeof raw !== "object") throw new PolicyCompileError("the compiler did not return a rule object");
  const withId = { ...(raw as Record<string, unknown>), id: `user-${randomBytes(3).toString("hex")}` };
  const parsed = PolicyRule.safeParse(withId);
  if (!parsed.success) {
    throw new PolicyCompileError(parsed.error.issues.slice(0, 3).map((i) => `${i.path.join(".") || "rule"}: ${i.message}`).join("; "));
  }
  const rule = parsed.data;
  const { tool, argsCondition } = rule.match;
  if (tool !== "*") {
    if (!agentTools.includes(tool as ToolName)) throw new PolicyCompileError(`“${tool}” is not a tool the agent can call`);
    for (const k of Object.keys(argsCondition ?? {})) {
      if (!(k in ARG_SHAPES[tool as ToolName])) throw new PolicyCompileError(`${tool} has no argument “${k}”`);
    }
  } else if (argsCondition && Object.keys(argsCondition).length) {
    throw new PolicyCompileError("argument conditions need a specific tool, not “*”");
  }
  return rule;
}

function parseJson(text: string): unknown {
  const t = text.trim().replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "");
  try {
    return JSON.parse(t);
  } catch {
    const a = t.indexOf("{");
    const b = t.lastIndexOf("}");
    if (a >= 0 && b > a) return JSON.parse(t.slice(a, b + 1));
    throw new PolicyCompileError("the compiler's reply was not valid JSON");
  }
}

export interface CompiledPolicy {
  rule: PolicyRule;
  readback: string;
  warnings: string[];
}

/**
 * Plain-language rule -> validated draft. The LLM sees only the user's own typed sentence (trusted) and the tool list.
 * Retries once with the validation error. The result is a DRAFT: nothing is saved here.
 */
export async function compilePolicy(llm: LlmAdapter, text: string): Promise<CompiledPolicy> {
  const sentence = text.trim();
  let feedback = "";
  let lastError = "unknown error";
  for (let attempt = 0; attempt < 2; attempt++) {
    const reply = await llm.complete({
      system: COMPILER_SYSTEM,
      user: `User's rule: ${JSON.stringify(sentence)}${feedback}`,
      json: true,
      maxTokens: 1024,
    });
    try {
      const obj = parseJson(reply) as { rule?: unknown; error?: unknown };
      if (typeof obj.error === "string" && !obj.rule) throw new PolicyCompileError(`This rule can't be expressed: ${obj.error.slice(0, 200)}`);
      const rule = validateCandidate(obj.rule);
      const base = rule.id.replace(RULE_KEYS_FOR_ID, "-");
      return { rule: { ...rule, id: base }, readback: describeRule(rule), warnings: ruleWarnings(rule) };
    } catch (e) {
      if (e instanceof LlmError) throw e;
      lastError = e instanceof Error ? e.message : String(e);
      // A deliberate "cannot be expressed" answer is final; only structural problems are retried.
      if (lastError.startsWith("This rule can't be expressed")) throw new PolicyCompileError(lastError);
      feedback = `\n\nYour previous reply was rejected (${lastError}). Reply again with ONLY the corrected JSON object.`;
    }
  }
  throw new PolicyCompileError(`Couldn't turn that into a valid rule (${lastError}). Try rephrasing, or use the JSON editor below.`);
}

/** Server-side holding area for compiled drafts. Only an explicit confirm of a stored draft can save it. */
export class PolicyDrafts {
  private readonly drafts = new Map<string, { policy: CompiledPolicy; text: string; expires: number }>();
  constructor(private readonly ttlMs = 15 * 60_000, private readonly now: () => number = Date.now) {}

  add(policy: CompiledPolicy, text: string) {
    const id = randomBytes(8).toString("hex");
    this.sweep();
    this.drafts.set(id, { policy, text, expires: this.now() + this.ttlMs });
    return { id, expiresAt: this.now() + this.ttlMs };
  }

  /** Removes and returns the draft (single use). */
  take(id: string) {
    this.sweep();
    const d = this.drafts.get(id);
    if (d) this.drafts.delete(id);
    return d ?? null;
  }

  discard(id: string) {
    return this.drafts.delete(id);
  }

  private sweep() {
    for (const [k, v] of this.drafts) if (v.expires <= this.now()) this.drafts.delete(k);
  }
}
