/**
 * Attack evaluation: runs the full pipeline (sandbox mailbox + fixtures/attacks, quarantined extraction, provenance, Guard,
 * executor) against 20 prompt-injection emails and 10 benign-but-suspicious emails, with a worst-case scripted agent.
 *   npm run eval:attacks            offline, deterministic (scripted worst-case extractor)
 *   npm run eval:attacks -- --live  real extractor LLM from .env (paced, uses quota)
 * Writes docs/eval-results.md and docs/eval-results.json. The numbers are whatever the run produced.
 */
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadConfig } from "../src/config.js";
import { renderEvalMarkdown, runAttackEval } from "../src/eval/attacks.js";
import { createLlm } from "../src/llm/index.js";

process.env.NODE_ENV = "test"; // silence request logging
const live = process.argv.includes("--live");
let llm;
if (live) {
  const made = createLlm(loadConfig());
  if ("error" in made) {
    console.error(`Cannot run --live: ${made.error}`);
    process.exit(1);
  }
  llm = made.llm;
}
let commit: string | null = null;
try {
  commit = execSync("git rev-parse --short HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
} catch {
  /* not a git checkout */
}

console.log(`Attack evaluation (SANDBOX DATA) | mode=${live ? "live" : "scripted-worst-case"}\n`);
try {
  const result = await runAttackEval({ llm, commit, log: (m) => console.log(m) });
  const docs = resolve(dirname(fileURLToPath(import.meta.url)), "../../../docs");
  mkdirSync(docs, { recursive: true });
  writeFileSync(resolve(docs, "eval-results.json"), JSON.stringify(result, null, 2) + "\n");
  writeFileSync(resolve(docs, "eval-results.md"), renderEvalMarkdown(result));
  const a = result.attacks;
  const b = result.benign;
  // Keep the README's numbers in sync with the run (generated, never typed by hand).
  const readme = resolve(docs, "../README.md");
  if (existsSync(readme)) {
    const src = readFileSync(readme, "utf8");
    const block = [
      "<!-- EVAL:START (generated by npm run eval:attacks) -->",
      `Latest run: ${result.date.slice(0, 10)}, mode \`${result.mode}\`, extractor \`${result.extractorModel}\`, SANDBOX DATA. Full report: [docs/eval-results.md](docs/eval-results.md).`,
      "",
      "| Metric | Result |",
      "|---|---|",
      `| Attack emails blocked or flagged (either layer) | ${a.defended}/${a.total} |`,
      `| Flagged at ingestion / stopped by the Guard | ${a.flagged}/${a.total} / ${a.guardStopped}/${a.total} |`,
      `| **Attacker-controlled actions executed without the user** | **${a.executedAttackerActions}** |`,
      `| Benign look-suspicious emails flagged (false positives) | ${b.flagged}/${b.total} |`,
      `| Benign tasks completed | ${b.tasksCompleted}/${b.total} |`,
      "<!-- EVAL:END -->",
    ].join("\n");
    const re = /<!-- EVAL:START[\s\S]*?<!-- EVAL:END -->/;
    if (re.test(src)) writeFileSync(readme, src.replace(re, () => block));
  }
  console.log("\n=== RESULTS ===");
  console.log(`attacks flagged at ingestion:        ${a.flagged}/${a.total}`);
  console.log(`attacker action blocked or gated:    ${a.guardStopped}/${a.total}`);
  console.log(`blocked or flagged (either layer):   ${a.defended}/${a.total}`);
  console.log(`attacker actions EXECUTED (want 0):  ${a.executedAttackerActions}`);
  console.log(`benign emails flagged (FP):          ${b.flagged}/${b.total}`);
  console.log(`benign tasks completed:              ${b.tasksCompleted}/${b.total}`);
  console.log(`stress (user approves everything):   ${result.stress.effectsCreated} effects from ${result.stress.pendingAttackerActions} pending`);
  console.log("\nWrote docs/eval-results.md and docs/eval-results.json");
  if (a.executedAttackerActions > 0) process.exitCode = 2;
} catch (e) {
  console.error(`Eval failed: ${e instanceof Error ? e.message : e}`);
  process.exitCode = 1;
}
process.exit(process.exitCode ?? 0);
